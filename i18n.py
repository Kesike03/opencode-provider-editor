def _language_code(value):
    value = (value or '').strip().lower()
    if value.startswith('chinese'):
        return 'zh'
    if value.startswith('english'):
        return 'en'
    code = value.split('.', 1)[0].split('_', 1)[0].split('-', 1)[0]
    return code if code in LANGUAGES else ''


def default_language():
    """Pick a supported language from an override or the system locale."""
    override = _language_code(os.environ.get('OPENCODE_EDITOR_LANG'))
    if override:
        return override
    for name in ('LC_ALL', 'LC_MESSAGES', 'LANG'):
        code = _language_code(os.environ.get(name))
        if code:
            return code
    try:
        system = locale.getlocale()[0]
    except ValueError:
        system = ''
    return _language_code(system) or 'zh'


def set_language(language):
    if language not in LANGUAGES:
        raise ValueError('Unsupported language: ' + str(language))
    _STATE['language'] = language


def get_language():
    return _STATE['language']


def tr(message_id, **values):
    """Translate a message ID, with named %-placeholders for dynamic values."""
    template = CATALOG.get(_STATE['language'], {}).get(message_id)
    if template is None:
        template = CATALOG['zh'].get(message_id, message_id)
    return template % values if values else template
